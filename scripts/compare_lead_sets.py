"""Test-set (fold 10) comparison of the 3-lead baseline and the Lead I models.

Reads results/<lead set>/preds_*.npz and evaluates each models/<lead set>/
tinyml_1d_cnn_int8.tflite directly, then writes
results/lead_set_comparison.csv and results/lead_set_comparison.md.

    python scripts/compare_lead_sets.py
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import f1_score, roc_auc_score

sys.path.insert(0, str(Path(__file__).resolve().parent))
from project import CACHE_FILE, CNN_INPUT_NORMS, LEAD_SETS, ROOT, normalize_cnn_input  # noqa: E402

MODELS = [  # (display name, preds file, key)
    ("XGBoost (tabular)", "preds_classical.npz", "xgb"),
    ("Random Forest (tabular)", "preds_classical.npz", "rf"),
    ("1D-CNN float32", "preds_1dcnn.npz", "cnn1d"),
    ("1D-CNN INT8 (deployed)", None, None),
    ("STFT 2D-CNN", "preds_2dcnn.npz", "cnn2d"),
    ("ResNet + attention (ceiling)", "preds_sota.npz", "sota"),
]


def int8_predictions(tflite_path, X):
    import tensorflow as tf
    # Reference kernels: match TFLM/CMSIS-NN on the device (XNNPACK rounds differently).
    it = tf.lite.Interpreter(model_path=str(tflite_path),
                             experimental_op_resolver_type=tf.lite.experimental.OpResolverType.BUILTIN_REF)
    it.allocate_tensors()
    i, o = it.get_input_details()[0], it.get_output_details()[0]
    s, z = i["quantization"]
    so, zo = o["quantization"]
    out = np.empty((len(X), o["shape"][-1]), np.float32)
    for k in range(len(X)):
        it.set_tensor(i["index"], np.clip(np.round(X[k:k + 1] / s + z), -128, 127).astype(np.int8))
        it.invoke()
        out[k] = (it.get_tensor(o["index"])[0].astype(np.float32) - zo) * so
    return out


def to_markdown(df):
    """Minimal DataFrame -> markdown table (avoids the optional 'tabulate' dependency)."""
    df = df.reset_index()
    cols = [str(c) for c in df.columns]
    fmt = lambda v: f"{v:.4f}" if isinstance(v, (float, np.floating)) and not np.isnan(v) else ("" if v is None or (isinstance(v, float) and np.isnan(v)) else str(v))
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in df.itertuples(index=False)]
    return "\n".join(lines)


def main():
    cache = np.load(CACHE_FILE, allow_pickle=True)
    y_test, class_names = cache["y_test"], list(cache["class_names"])
    rows = []
    for lead_set, leads in LEAD_SETS.items():
        res, mod = ROOT / "results" / lead_set, ROOT / "models" / lead_set
        for name, fname, key in MODELS:
            if fname is None:
                tfl = mod / "tinyml_1d_cnn_int8.tflite"
                if not tfl.exists():
                    continue
                X = normalize_cnn_input(cache["X_test"][:, :, leads], CNN_INPUT_NORMS[lead_set])
                preds = int8_predictions(tfl, X)
            else:
                if not (res / fname).exists():
                    continue
                preds = np.load(res / fname)[key]
            row = {"lead_set": lead_set, "model": name,
                   "macro_auc": roc_auc_score(y_test, preds, average="macro"),
                   "macro_f1@0.5": f1_score(y_test, (preds >= 0.5).astype(int), average="macro", zero_division=0)}
            for c, a in zip(class_names, roc_auc_score(y_test, preds, average=None)):
                row[f"auc_{c}"] = a
            rows.append(row)

    df = pd.DataFrame(rows)
    out_csv = ROOT / "results" / "lead_set_comparison.csv"
    df.round(4).to_csv(out_csv, index=False)

    auc = df.pivot(index="model", columns="lead_set", values="macro_auc")
    auc = auc.reindex([m[0] for m in MODELS]).dropna(how="all")
    auc["delta"] = auc.get("lead1") - auc.get("3lead")
    per_class = df.set_index(["model", "lead_set"])[[f"auc_{c}" for c in class_names]]
    md = ["# 3-lead vs Lead I (PTB-XL fold 10, n = %d)" % len(y_test), "",
          "Generated by `scripts/compare_lead_sets.py`. Macro AUC:", "",
          to_markdown(auc), "", "Per-class AUC:", "", to_markdown(per_class), ""]
    out_md = ROOT / "results" / "lead_set_comparison.md"
    out_md.write_text("\n".join(md), encoding="utf8")
    print("\n".join(md))
    print(f"wrote {out_csv} and {out_md}")


if __name__ == "__main__":
    main()

"""Generate firmware/rak11300_bench/bench_vectors.h: a few PTB-XL Lead I windows
(int16, 0.001 mV/LSB) with the Python reference outputs, so the board can check
its own results while it measures latency.

    python scripts/make_bench_vectors.py
"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import orchestrator as O  # noqa: E402
import project as P  # noqa: E402
from noise_stress import add_noise  # noqa: E402
from reference_features import FEATURE_NAMES, extract_lead1_features  # noqa: E402

OUT = P.ROOT / "firmware" / "rak11300_bench" / "bench_vectors.h"


def pick(cache, p):
    """Fold-10 windows that exercise different code paths."""
    X = cache["X_test"][:, :, 0].astype(np.float64)
    y = cache["y_test"]
    names = list(cache["class_names"])
    feats = cache["X_feat_v2_test"]
    qrs, cv, pr = feats[:, 13], feats[:, 7], feats[:, 12]
    norm, cd, mi = (y[:, names.index(c)] == 1 for c in ("NORM", "CD", "MI"))
    choices = [
        ("NORM, regular", np.where(norm & (cv < 0.03))[0][0]),
        ("CD, wide QRS", np.where(cd & (qrs >= 130))[0][0]),
        ("MI", np.where(mi & ~cd)[0][0]),
        ("irregular, no P wave", np.where((cv > 0.15) & np.isnan(pr))[0][0]),
        ("tachycardic", np.where(feats[:, 0] > 110)[0][0]),
    ]
    wins = [(label, X[i]) for label, i in choices]
    rng = np.random.default_rng(7)
    wins.append(("NORM + electrode motion -6 dB", add_noise(X[choices[0][1]][None], "em", -6, rng, half=1)[0]))
    return wins


def c_float(v):
    return "NAN" if np.isnan(v) else f"{v:.9e}f"  # always has a '.', e.g. 1.300000000e+03f


def main():
    cache = np.load(P.CACHE_FILE, allow_pickle=True)
    p = json.loads(O.PARAMS_JSON.read_text(encoding="utf-8"))
    rows = []
    for label, mv in pick(cache, p):
        adc = O.to_adc(mv)
        f, npk, q = extract_lead1_features(adc.astype(np.float64) * O.MV_PER_LSB, with_quality=True)
        quality = O.gate(adc, f, npk, q, p)
        rows.append((label, adc, f, npk, quality, O.rhythm_flags(f, p)))

    lines = ["// GENERATED by scripts/make_bench_vectors.py -- do not edit.",
             "// PTB-XL fold-10 Lead I windows at 0.001 mV/LSB with Python reference outputs.",
             "#ifndef BENCH_VECTORS_H_", "#define BENCH_VECTORS_H_", "", "#include <math.h>",
             "#include <stdint.h>", "", f"#define BENCH_NUM_WINDOWS {len(rows)}",
             f"#define BENCH_NUM_FEATURES {len(FEATURE_NAMES)}", "",
             "// Feature order: " + ", ".join(FEATURE_NAMES), ""]
    lines.append("static const char* const kBenchLabel[BENCH_NUM_WINDOWS] = {"
                 + ", ".join(f'"{r[0]}"' for r in rows) + "};")
    lines.append("static const int16_t kBenchAdc[BENCH_NUM_WINDOWS][1000] = {")
    for r in rows:
        vals = r[1].tolist()
        lines.append("  {" + ",".join(str(v) for v in vals) + "},")
    lines.append("};")
    lines.append("static const float kBenchExpected[BENCH_NUM_WINDOWS][BENCH_NUM_FEATURES] = {")
    for r in rows:
        lines.append("  {" + ", ".join(c_float(v) for v in r[2]) + "},")
    lines.append("};")
    lines.append("static const uint8_t kBenchExpectedPeaks[BENCH_NUM_WINDOWS] = {"
                 + ", ".join(str(r[3]) for r in rows) + "};")
    lines.append("static const uint8_t kBenchExpectedQuality[BENCH_NUM_WINDOWS] = {"
                 + ", ".join(str(r[4]) for r in rows) + "};")
    lines.append("static const uint8_t kBenchExpectedFlags[BENCH_NUM_WINDOWS] = {"
                 + ", ".join(str(r[5]) for r in rows) + "};")
    lines += ["", "#endif  // BENCH_VECTORS_H_", ""]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8")
    for r in rows:
        print(f"{r[0]:<32} peaks={r[3]:2d} quality={r[4]:2d} flags={r[5]:2d} qrs={r[2][13]:.1f} pr={r[2][12]:.1f}")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
